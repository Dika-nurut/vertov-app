import type { StructurizeCorpusEntry } from '../../src/scenario-structurize-eval';

/**
 * Structurization eval corpus (goal S1) — the release gate's reference set.
 *
 * 10 reference ideas per format (film / social / ad / sketch), each paired with
 * a human-authored "good answer" (`reference`). In CI the mock gateway replays
 * the reference so the rubric + parse pipeline are locked zero-spend; the same
 * ideas drive the opt-in LIVE eval (STRUCTURIZE_LIVE_EVAL=1) that actually
 * scores a real model and blocks a prompt/model change on a score drop.
 *
 * Every reference is authored to PASS the rubric: right format, beat durations
 * that sum to the target (non-film), concrete beats (never placeholders), and a
 * clarifying question ONLY on the deliberately-underspecified entries.
 */

type Beat = {
  kind: string;
  title: string;
  summary: string;
  durationSeconds?: number;
  visual?: string;
  spokenText?: string;
  onScreenText?: string;
};

/** Compact beat builder — keeps entries readable and durations explicit. */
function beat(
  kind: string,
  title: string,
  summary: string,
  durationSeconds?: number,
  extra: Partial<Beat> = {},
): Beat {
  return { kind, title, summary, ...(durationSeconds ? { durationSeconds } : {}), ...extra };
}

function ref(
  format: string,
  brief: Record<string, unknown>,
  beats: Beat[],
  question?: string,
): unknown {
  return {
    format,
    brief: { version: 1, ...brief },
    outline: { version: 1, beats },
    ...(question ? { question } : {}),
  };
}

